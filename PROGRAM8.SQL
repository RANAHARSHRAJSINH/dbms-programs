--Write a PL/SQL block to delete the record of employee for given EID.

SET SERVEROUTPUT ON
SET VERIFY OFF
SET FEEDBACK OFF

DECLARE
	E_EID EMP.EID%TYPE;
	CO NUMBER(3);
BEGIN
	E_EID:=&E_EID;
	SELECT COUNT(*) INTO CO FROM EMP WHERE EID=E_EID;
	
	IF CO = 0 THEN
		DBMS_OUTPUT.PUT_LINE('RECORD NOT FOUND');
	ELSE 
		DELETE FROM EMP WHERE EID=E_EID;
		DBMS_OUTPUT.PUT_LINE('RECORD DELETED SUCCESSFULLY');
	END IF;


END;
/
SET SERVEROUTPUT OFF

