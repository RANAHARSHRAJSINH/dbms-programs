--SECOND PROGRAM

SET SERVEROUTPUT ON'
SET VERIFY OFF
SET FEEDBACK OFF 

ACCEPT PN PROMPT "ENTER THE PRODUT NAME:"
ACCEPT PR PROMPT "ENTER THE PRODUCT PRICE:"
ACCEPT QN PROMPT "ENTER THE PRODUT QUNTITY:"
ACCEPT DS PROMPT "ENTER THE DISOUNT:"

DECLARE 
	PNAME VARCHAR(20);
	QTY NUMBER(5);
	PRICE NUMBER(7,2);
	TP NUMBER(7,2);
	DISCOUNT NUMBER(5);
	FP NUMBER(7,2);
BEGIN
	PNAME:='&PN';
	QTY:=&QN;
	PRICE:=&PR;
	DISCOUNT:=&DS;
	TP:=QTY*PRICE;
	FP:=(TP-(TP*DISCOUNT/100));
	
	DBMS_OUTPUT.PUT_LINE('THE PRODUCT NAME IS:-'||PNAME);
	DBMS_OUTPUT.PUT_LINE('TOTAL QTY IS:-'||QTY);
	DBMS_OUTPUT.PUT_LINE('PRICE :-'||PRICE);
	DBMS_OUTPUT.PUT_LINE('TOTAL PRICE :-'||TP);
	DBMS_OUTPUT.PUT_LINE('DISCOUNT: - '||(TP*DISCOUNT)/100);
	DBMS_OUTPUT.PUT_LINE('FINAL PRICE :-'||FP);
END;
/
SET SERVEROUTPUT OFF