--USE IF STATEMENT IN MULTIPLE OPRATTION

ACCEPT CHOICE PROMPT "ENTER YOUR CHOICE: 1. AREA OF CIRCLE, 2. AREA OF RECTANGLE, 3. CIRCUMFERENCE OF CIRCLE: "

SET SERVEROUTPUT ON
SET FEEDBACK OFF
SET VERIFY OFF

DECLARE
	C NUMBER:=&CHOICE;
	PI CONSTANT NUMBER(3,2) := 3.14;
	R NUMBER(5);
	CAREA NUMBER(7,2);

	L NUMBER(4);
	W NUMBER(6);
	RAREA NUMBER(7,2);

 	CIR NUMBER(7,2);
BEGIN
	IF(C=1) THEN
	R:=&R;
	DBMS_OUTPUT.PUT_LINE('1.AREA OF CIRCLE');
	DBMS_OUTPUT.PUT_LINE('================');
	CAREA:=PI*POWER(R,2);
	DBMS_OUTPUT.PUT_LINE('AREA OF CIRCLE IS: '||CAREA);
	DBMS_OUTPUT.PUT_LINE('================');
	DBMS_OUTPUT.PUT_LINE('');
	ELSIF(C=2) THEN
	L:=&L;
	W:=&W;
	DBMS_OUTPUT.PUT_LINE('2.AREA OF RECTNGLE');
	DBMS_OUTPUT.PUT_LINE('================');
	RAREA:=L*W;
	DBMS_OUTPUT.PUT_LINE('AREA OF RECTANGLE IS: '||RAREA);
	DBMS_OUTPUT.PUT_LINE('================');
	DBMS_OUTPUT.PUT_LINE('');
	ELSIF(C=3) THEN
	DBMS_OUTPUT.PUT_LINE('2.CERCAMFRANCE OF CIRCLE');
	DBMS_OUTPUT.PUT_LINE('================');
	CIR:=PI*2*R;
	DBMS_OUTPUT.PUT_LINE('CERCAMFRANCE OF CIRCLE: '||CIR);
	DBMS_OUTPUT.PUT_LINE('================');
	DBMS_OUTPUT.PUT_LINE('');
	END IF;
END;
/
SET SERVEROUTPUT OFF